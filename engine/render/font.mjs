/** GLYPHS[char] = list of [x, y, width] runs on the 5x7 grid */
export const GLYPHS = {};
for (const [ch, def] of Object.entries(RAW)) {
  const rows = def.split(' ');
  if (rows.length !== 7 || rows.some((r) => r.length !== 5)) throw new Error(`Bad glyph: ${ch}`);
  const runs = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < 5) {
      if (row[x] !== '#') { x++; continue; }
      let e = x;
      while (e < 5 && row[e] === '#') e++;
      runs.push([x, y, e - x]);
      x = e;
    }
  });
  GLYPHS[ch] = runs;
}
export const hasGlyphs = (s) => [...s].every((c) => GLYPHS[c] !== undefined);
/** Width of a string in font pixels (letters are 5 wide with 1 gap). */
export const textUnits = (s) => Math.max(0, [...s].length * 6 - 1);
